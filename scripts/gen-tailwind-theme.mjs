// Generates packages/tailwind/src/tailwind-theme.ts: the theme CSS of the pinned tailwindcss
// (`@import "tailwindcss/theme"`), as text for the browser entry, which cannot read it from disk.
// scripts/check-generated.sh checks it is up to date.
//   node scripts/gen-tailwind-theme.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(`${root}packages/tailwind/package.json`);
const pkg = require('tailwindcss/package.json');
const css = readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8');

writeFileSync(
  `${root}packages/tailwind/src/tailwind-theme.ts`,
  `// Generated by scripts/gen-tailwind-theme.mjs from tailwindcss ${pkg.version}'s theme.css (MIT); do not edit.

/** Tailwind's theme, what \`@import "tailwindcss/theme"\` loads. */
export const TAILWIND_THEME_CSS = ${JSON.stringify(css)};
`,
);
