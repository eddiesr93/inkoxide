// Generates packages/schema/index.d.ts from packages/schema/document.v1.json:
//   node scripts/gen-schema-types.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { compile } from 'json-schema-to-typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const raw = readFileSync(`${root}packages/schema/document.v1.json`, 'utf8');
const schema = JSON.parse(raw);

// Stable type names: the root is `Document`, every definition keeps its
// `$defs` key (titles would otherwise become type names).
const input = structuredClone(schema);
input.title = 'Document';
for (const [name, def] of Object.entries(input.$defs)) def.title = name;
// `Node` checks `type` before `oneOf` for better validation errors; in
// TypeScript the variants alone make a discriminated union.
input.$defs.Node = { title: 'Node', oneOf: input.$defs.Node.oneOf };
// "Exactly one of a or b" (`oneOf` of `required` clauses) has no useful
// TypeScript form and would add an index signature; both stay optional
// in the types and the engine or ajv reports the conflict.
for (const def of Object.values(input.$defs)) {
  if (def.oneOf?.every((b) => b.required && !b.$ref && !b.type)) delete def.oneOf;
}
// "One of these objects" (a transform function, a track): TypeScript lets
// an object literal mix the keys of a union's members, so each object
// member forbids the others' keys (`rotate?: never`). A member that is
// itself such a union (`TrackSize` in `TemplateTrack`) is inlined first.
const isObject = (b) => b.type === 'object' && b.properties;
for (const def of Object.values(input.$defs)) {
  if (!def.oneOf) continue;
  def.oneOf = def.oneOf.flatMap((b) => {
    const target = b.$ref && input.$defs[b.$ref.split('/').pop()];
    return target?.oneOf?.some(isObject) ? structuredClone(target.oneOf) : [b];
  });
  const objects = def.oneOf.filter(isObject);
  if (objects.length < 2) continue;
  for (const o of objects) {
    for (const other of objects) {
      for (const k of Object.keys(other.properties)) o.properties[k] ??= { tsType: 'never' };
    }
  }
}
// A `$ref` with a sibling `description` would become a new, renamed type
// carrying that description; keep the named type and document the use.
(function wrapRefs(v) {
  if (Array.isArray(v)) return v.forEach(wrapRefs);
  if (!v || typeof v !== 'object') return;
  for (const k of Object.keys(v)) {
    const c = v[k];
    if (c && typeof c === 'object' && !Array.isArray(c) && c.$ref && Object.keys(c).length > 1) {
      const { $ref, ...rest } = c;
      v[k] = { ...rest, allOf: [{ $ref }] };
    }
    wrapRefs(v[k]);
  }
})(input);

const banner = `// Generated by scripts/gen-schema-types.mjs from document.v1.json.
// Do not edit; change the schema and regenerate.`;
const types = await compile(input, 'Document', {
  bannerComment: banner,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  style: { singleQuote: true, printWidth: 100 },
});

const exports = `
/** The document \`version\` this schema describes. */
export declare const SCHEMA_VERSION: 1;
/** The JSON Schema (draft 2020-12), for client-side validation with e.g. ajv. */
export declare const schema: Record<string, unknown>;
/**
 * The engine's error path (\`pages[0].children[3].font\`) for an ajv error.
 * For \`additionalProperties\` and \`required\` errors the offending
 * property is appended, as the engine does.
 */
export declare function enginePath(error: {
  instancePath: string;
  keyword?: string;
  params?: Record<string, unknown>;
}): string;
`;

writeFileSync(`${root}packages/schema/index.d.ts`, types + exports);
