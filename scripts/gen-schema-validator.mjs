// Generates packages/tree/src/tree/schema-validator.ts: ajv's standalone validator for
// packages/schema/document.v1.json, as the code ajv would compile at run time, so that validating
// a tree in development compiles nothing (a Content Security Policy without 'unsafe-eval' allows
// it, and ajv is not needed at run time). scripts/check-generated.sh checks it is up to date.
//   node scripts/gen-schema-validator.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
// ajv is a dev dependency of @inkoxide/tree.
const require = createRequire(`${root}packages/tree/package.json`);
const { Ajv2020 } = require('ajv/dist/2020.js');
const standalone = require('ajv/dist/standalone').default;
const addFormats = require('ajv-formats');

const schema = JSON.parse(readFileSync(`${root}packages/schema/document.v1.json`, 'utf8'));
// The options validate.ts used to compile with; the schema's one format is `date-time`.
const ajv = new Ajv2020({
  discriminator: true,
  strict: false,
  allErrors: false,
  code: { source: true, esm: true, optimize: true },
});
addFormats(ajv, ['date-time']);
let code = standalone(ajv, ajv.compile(schema));

// ajv refers to its runtime with require(), even for an ES module: the one function it uses comes
// in the file, and the format from ajv-formats, which stays a dependency.
const replace = (from, to) => {
  if (!code.includes(from)) throw new Error(`gen-schema-validator: ajv's output has no ${from}`);
  code = code.replaceAll(from, to);
};
replace('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
replace('require("ajv-formats/dist/formats").fullFormats["date-time"]', "fullFormats['date-time']");
replace('"use strict";export const validate = validate20;export default validate20;', '');
if (/require\(/.test(code)) throw new Error('gen-schema-validator: ajv refers to another module');

writeFileSync(
  `${root}packages/tree/src/tree/schema-validator.ts`,
  `// Generated by scripts/gen-schema-validator.mjs from packages/schema/document.v1.json; do not edit.
// @ts-nocheck
import { fullFormats } from 'ajv-formats/dist/formats.js';

/** The length of a string in code points, as JSON Schema counts it (ajv's ucs2length). */
function ucs2length(str) {
  let n = 0;
  for (const _ of str) n++;
  return n;
}

${code}

/** Whether \`data\` is a valid document; its problems are then in \`validate.errors\`. */
export const validate = validate20;
`,
);
