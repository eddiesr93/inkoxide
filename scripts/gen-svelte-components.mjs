// Generates packages/svelte/src/components/<Name>.svelte: one component per Inkoxide component,
// each rendering its element (`<ink-view data-ink>`) and putting its props in the render's table
// (packages/svelte/src/capture.ts). scripts/check-generated.sh checks the files are up to date.
//   node scripts/gen-svelte-components.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../packages/svelte/src/components/', import.meta.url));

/** Each component: its name, its element, and the type of its props in @inkoxide/tree. */
const COMPONENTS = [
  ['Document', 'DocumentProps'],
  ['Page', 'PageProps'],
  ['Header', 'HeaderProps'],
  ['Footer', 'FooterProps'],
  ['View', 'ViewProps'],
  ['Text', 'TextProps | SvgTextProps'],
  ['Link', 'LinkProps'],
  ['Image', 'ImageProps'],
  ['ImageBackground', 'ImageBackgroundProps'],
  ['Table', 'TableProps'],
  ['Row', 'RowProps'],
  ['Cell', 'CellProps'],
  ['PageNumber', 'Record<string, never>'],
  ['TotalPages', 'Record<string, never>'],
  ['PageBreak', 'PageBreakProps'],
  ['Spacer', 'SpacerProps'],
  ['Field', 'FieldProps'],
  ['FieldSet', 'FieldSetProps'],
  ['Note', 'NoteProps'],
  ['Attachment', 'AttachmentProps'],
  ['Canvas', 'CanvasProps'],
  ['Svg', 'SvgProps'],
  ['G', 'SvgElementProps'],
  ['Path', 'PathProps'],
  ['Rect', 'RectProps'],
  ['Circle', 'CircleProps'],
  ['Ellipse', 'EllipseProps'],
  ['Line', 'LineProps'],
  ['Polyline', 'PolyProps'],
  ['Polygon', 'PolyProps'],
  ['Defs', 'DefsProps'],
  ['ClipPath', 'ClipPathProps'],
  ['Marker', 'MarkerProps'],
  ['Tspan', 'TspanProps'],
  ['TextPath', 'TextPathProps'],
  ['LinearGradient', 'GradientProps'],
  ['RadialGradient', 'GradientProps'],
  ['Stop', 'StopProps'],
  ['TextField', 'TextFieldProps'],
  ['TextInput', 'TextFieldProps'],
  ['Checkbox', 'CheckboxProps'],
  ['Radio', 'RadioProps'],
  ['Select', 'SelectProps'],
  ['List', 'ListProps'],
];

const kebab = (name) => name.replace(/[A-Z]/g, (c, i) => `${i ? '-' : ''}${c.toLowerCase()}`);

for (const [name, props] of COMPONENTS) {
  const tag = `ink-${kebab(name)}`;
  const types = [...new Set(props.match(/[A-Z]\w+Props/g) ?? [])].sort();
  writeFileSync(
    `${dir}${name}.svelte`,
    `<!-- Generated by scripts/gen-svelte-components.mjs; do not edit. -->
<script lang="ts">
  import type { PageInfo${types.map((t) => `, ${t}`).join('')} } from '@inkoxide/tree';
  import type { Snippet } from 'svelte';

  import { capture } from '../capture.ts';

  type Props = Omit<${props}, 'children' | 'render'> & {
    class?: unknown;
    children?: Snippet;
    render?: Snippet<[PageInfo]>;
  };

  let { children, render, ...props }: Props = $props();
  // A template renders once: the table keeps the props object, read when the render is done.
  // svelte-ignore state_referenced_locally
  const id = capture('${tag}', props, render);
</script>

<${tag} data-ink={id}>{@render children?.()}</${tag}>
`,
  );
}

const exports = COMPONENTS.map(([name]) => `export { default as ${name} } from './${name}.svelte';\n`).join(
  '',
);
writeFileSync(
  `${dir}index.ts`,
  `// Generated by scripts/gen-svelte-components.mjs; do not edit.\n${exports}`,
);
