// Generates packages/svelte/src/components/: for each Inkoxide component (`COMPONENTS` of
// @inkoxide/tree), `<Name>.svelte`, which renders its element (`<ink-view data-ink>`) and enters its
// props in the render's props table (packages/svelte/src/table.ts), and `<Name>.svelte.d.ts`, its
// types; and `index.ts`, which exports them. scripts/check-generated.sh checks the files are up to
// date.
//   node scripts/gen-svelte-components.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { COMPONENTS, tagName } from '../packages/tree/src/components/index.ts';

const dir = fileURLToPath(new URL('../packages/svelte/src/components/', import.meta.url));

const GENERATED = 'Generated by scripts/gen-svelte-components.mjs; do not edit.';

/** The props of a component in Svelte: its own, but `children` and `render`, which are snippets. */
const propsType = (props) => `Omit<${props}, 'children' | 'render'> & {
  class?: unknown;
  children?: Snippet;
  render?: Snippet<[PageInfo]>;
}`;

const imports = `import type { PageInfo, PropsByComponent } from '@inkoxide/tree';`;

for (const name of COMPONENTS) {
  const props = `PropsByComponent['${name}']`;
  const tag = tagName(name);
  writeFileSync(
    `${dir}${name}.svelte`,
    `<!-- ${GENERATED} -->
<script lang="ts">
  ${imports}
  import type { Snippet } from 'svelte';

  import { enter } from '../table.ts';

  type Props = ${propsType(props).replaceAll('\n', '\n  ')};

  let { children, render, ...props }: Props = $props();
  // A template renders once: the table keeps the props object, read when the render is done.
  // svelte-ignore state_referenced_locally
  const id = enter('${tag}', props, render);
</script>

<${tag} data-ink={id}>{@render children?.()}</${tag}>
`,
  );
  writeFileSync(
    `${dir}${name}.svelte.d.ts`,
    `// ${GENERATED}
${imports}
import type { Component, Snippet } from 'svelte';

/** The props of \`<${name}>\`. */
type Props = ${propsType(props)};

declare const ${name}: Component<Props>;
export default ${name};
`,
  );
}

const exports = COMPONENTS.map((name) => `export { default as ${name} } from './${name}.svelte';\n`).join('');
writeFileSync(`${dir}index.ts`, `// ${GENERATED}\n${exports}`);
