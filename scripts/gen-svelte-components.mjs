// Generates packages/svelte/src/components/: for each Inkoxide component (`COMPONENTS` of
// @inkoxide/tree), `<Name>.svelte`, which renders its element (`<ink-view data-ink>`) and puts its
// props in the render's table (packages/svelte/src/capture.ts), and `<Name>.svelte.d.ts`, its
// types; and `index.ts`, which exports them. scripts/check-generated.sh checks the files are up to
// date.
//   node scripts/gen-svelte-components.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { COMPONENTS, tagName } from '../packages/tree/src/components/index.ts';

const dir = fileURLToPath(new URL('../packages/svelte/src/components/', import.meta.url));

/** The type of each component's props in @inkoxide/tree. */
const PROPS = {
  Document: 'DocumentProps',
  Page: 'PageProps',
  Header: 'HeaderProps',
  Footer: 'FooterProps',
  View: 'ViewProps',
  Text: 'TextProps | SvgTextProps',
  Link: 'LinkProps',
  Image: 'ImageProps',
  ImageBackground: 'ImageBackgroundProps',
  Table: 'TableProps',
  Row: 'RowProps',
  Cell: 'CellProps',
  PageNumber: 'Record<string, never>',
  TotalPages: 'Record<string, never>',
  PageBreak: 'PageBreakProps',
  Spacer: 'SpacerProps',
  Field: 'FieldProps',
  FieldSet: 'FieldSetProps',
  Note: 'NoteProps',
  Attachment: 'AttachmentProps',
  Canvas: 'CanvasProps',
  Svg: 'SvgProps',
  G: 'SvgElementProps',
  Path: 'PathProps',
  Rect: 'RectProps',
  Circle: 'CircleProps',
  Ellipse: 'EllipseProps',
  Line: 'LineProps',
  Polyline: 'PolyProps',
  Polygon: 'PolyProps',
  Defs: 'DefsProps',
  ClipPath: 'ClipPathProps',
  Marker: 'MarkerProps',
  Tspan: 'TspanProps',
  TextPath: 'TextPathProps',
  LinearGradient: 'GradientProps',
  RadialGradient: 'GradientProps',
  Stop: 'StopProps',
  TextField: 'TextFieldProps',
  TextInput: 'TextFieldProps',
  Checkbox: 'CheckboxProps',
  Radio: 'RadioProps',
  Select: 'SelectProps',
  List: 'ListProps',
};

const missing = COMPONENTS.filter((name) => !(name in PROPS));
const extra = Object.keys(PROPS).filter((name) => !COMPONENTS.includes(name));
if (missing.length || extra.length) {
  throw new Error(
    `gen-svelte-components: the props types do not match @inkoxide/tree's COMPONENTS (missing: ${missing.join(', ') || 'none'}; not components: ${extra.join(', ') || 'none'})`,
  );
}

const GENERATED = 'Generated by scripts/gen-svelte-components.mjs; do not edit.';

/** The props of a component in Svelte: its own, but `children` and `render`, which are snippets. */
const propsType = (props) => `Omit<${props}, 'children' | 'render'> & {
  class?: unknown;
  children?: Snippet;
  render?: Snippet<[PageInfo]>;
}`;

for (const name of COMPONENTS) {
  const props = PROPS[name];
  const tag = tagName(name);
  const types = [...new Set(props.match(/[A-Z]\w+Props/g) ?? [])].sort();
  const imports = `import type { PageInfo${types.map((t) => `, ${t}`).join('')} } from '@inkoxide/tree';`;
  writeFileSync(
    `${dir}${name}.svelte`,
    `<!-- ${GENERATED} -->
<script lang="ts">
  ${imports}
  import type { Snippet } from 'svelte';

  import { capture } from '../capture.ts';

  type Props = ${propsType(props).replaceAll('\n', '\n  ')};

  let { children, render, ...props }: Props = $props();
  // A template renders once: the table keeps the props object, read when the render is done.
  // svelte-ignore state_referenced_locally
  const id = capture('${tag}', props, render);
</script>

<${tag} data-ink={id}>{@render children?.()}</${tag}>
`,
  );
  writeFileSync(
    `${dir}${name}.svelte.d.ts`,
    `// ${GENERATED}
${imports}
import type { Component, Snippet } from 'svelte';

/** The props of \`<${name}>\`. */
type Props = ${propsType(props)};

declare const ${name}: Component<Props>;
export default ${name};
`,
  );
}

const exports = COMPONENTS.map((name) => `export { default as ${name} } from './${name}.svelte';\n`).join('');
writeFileSync(`${dir}index.ts`, `// ${GENERATED}\n${exports}`);
