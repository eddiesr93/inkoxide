// Generates packages/react/src/version.ts from packages/react/package.json: the version the
// package gives React's developer tools, without reading package.json at run time (a browser
// bundle has no createRequire). scripts/release/stage.mjs runs it before building the package,
// and scripts/check-generated.sh checks the committed file is up to date.
//   node scripts/gen-react-version.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const { version } = JSON.parse(readFileSync(`${root}packages/react/package.json`, 'utf8'));
writeFileSync(
  `${root}packages/react/src/version.ts`,
  `// Generated by scripts/gen-react-version.mjs from packages/react/package.json; do not edit.\n\n` +
    `/** This package's version, given to React's developer tools. */\n` +
    `export const VERSION = ${JSON.stringify(version).replaceAll('"', "'")};\n`,
);
