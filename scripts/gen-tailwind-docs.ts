/**
 * Generates docs/TAILWIND_SUPPORT.md from packages/tailwind/src/supported.ts.
 * scripts/check-generated.sh runs it and fails when the committed file changes.
 *
 *   pnpm exec tsx scripts/gen-tailwind-docs.ts
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SUPPORTED, UNSUPPORTED } from '../packages/tailwind/src/supported.ts';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'TAILWIND_SUPPORT.md');
const esc = (s: string) => s.replaceAll('|', '\\|');

const groups = [...new Set(SUPPORTED.map((f) => f.group))];
let md = `# Supported Tailwind utilities

> Generated by \`scripts/gen-tailwind-docs.ts\` from \`packages/tailwind/src/supported.ts\`.
> Do not edit by hand. \`scripts/check-generated.sh\` fails when this file is stale.

Classes are compiled by the real Tailwind v4 compiler: every class is turned into CSS by
Tailwind and the CSS is mapped to the engine's style properties. A class works when
every CSS property it produces has an engine equivalent. The table below lists the families
that are supported and tested; each example is a unit test.

- Lengths are points: **1rem = 12pt**, **1px = 0.75pt**. \`p-4\` is 12pt,
  \`text-base\` 12pt. Use arbitrary values for exact sizes: \`text-[10.5pt]\`, \`p-[5pt_7pt]\`.
- Arbitrary lengths read as in the \`style\` prop: any absolute unit, \`calc()\`, and \`em\`
  (the element's font size; in \`text-[…]\`, the inherited one), \`vw\` and \`vh\` (1% of the
  page's width and height): \`w-[2em]\`, \`h-[10vh]\`.
- Arbitrary values (\`[…]\`) work for every supported property.
- Page variants (\`md:\`, \`landscape:\`, \`print:\`) read the page the element is on; see
  [Page variants](#page-variants).
- In development an unsupported class throws, naming the class and the CSS property; in
  production it is logged once and ignored.
- Text utilities on \`Page\`, \`View\`, \`Cell\` or \`Row\` are inherited by the text inside.

`;
for (const g of groups) {
  md += `## ${g}\n\n| Utilities | Engine property | Example → result | Notes |\n|---|---|---|---|\n`;
  for (const f of SUPPORTED.filter((x) => x.group === g)) {
    const [cls, style] = Object.entries(f.examples)[0] ?? ['', {}];
    md += `| ${esc(f.utilities)} | ${esc(f.maps)} | \`${esc(cls)}\` → \`${esc(JSON.stringify(style))}\` | ${esc(f.notes ?? '')} |\n`;
  }
  md += '\n';
}
md += `## Not supported\n\n| Example | Why |\n|---|---|\n`;
for (const u of UNSUPPORTED) md += `| \`${esc(u.example)}\` | ${esc(u.why)} |\n`;
md += `\nMissing something? [Open an issue](https://github.com/eddiesr93/inkoxide/issues) with the class and the\noutput you expect.\n`;

writeFileSync(OUT, md);
console.log(`wrote ${OUT}`);
